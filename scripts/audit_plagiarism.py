manuscript_dir = 'manuscript_revision_tacl/sections'
section_texts = {}
for f in sorted(os.listdir(manuscript_dir)):
    if f.endswith('.tex'):
        with open(os.path.join(manuscript_dir, f), encoding='utf-8') as fp:
            section_texts[f] = fp.read()

# Also include supplementary
with open('manuscript_revision_tacl/supplementary/supplementary_material.tex', encoding='utf-8') as fp:
    section_texts['supplementary_material.tex'] = fp.read()

def clean(text):
    text = re.sub(r'%.*', '', text)
    text = re.sub(r'\\[a-zA-Z]+(?:\*|\b)(?:\[[^\]]*\])?(?:\{([^}]*)\})?', r' \1 ', text)
    text = re.sub(r'[^a-zA-Z0-9\s]', ' ', text)
    return [w.lower() for w in text.split() if len(w) > 1]

def get_ngrams(tokens, n):
    return set(tuple(tokens[i:i+n]) for i in range(len(tokens) - n + 1))

def main():
    print('=' * 85)
    print('PLAGIARISM AND OVERLAP AUDIT: MANUSCRIPT VS. PUBLISHED PRIMARY LITERATURE')
    print('=' * 85)
    
    total_words = 0
    total_4g_matches = 0
    total_5g_matches = 0
    total_6g_matches = 0
    all_matched_phrases = []
    
    for sec_file, sec_raw in section_texts.items():
        sec_toks = clean(sec_raw)
        total_words += len(sec_toks)
        sec_3g = get_ngrams(sec_toks, 3)
        sec_4g = get_ngrams(sec_toks, 4)
        sec_5g = get_ngrams(sec_toks, 5)
        sec_6g = get_ngrams(sec_toks, 6)
        
        sec_m4 = 0
        sec_m5 = 0
        sec_m6 = 0
        
        for pub_name, pub_text in published_corpus.items():
            pub_toks = clean(pub_text)
            pub_4g = get_ngrams(pub_toks, 4)
            pub_5g = get_ngrams(pub_toks, 5)
            pub_6g = get_ngrams(pub_toks, 6)
            
            m4 = sec_4g & pub_4g
            m5 = sec_5g & pub_5g
            m6 = sec_6g & pub_6g
            
            sec_m4 += len(m4)
            sec_m5 += len(m5)
            sec_m6 += len(m6)
            
            if m5:
                for g in m5:
                    all_matched_phrases.append((' '.join(g), pub_name, sec_file))
                    
        total_4g_matches += sec_m4
        total_5g_matches += sec_m5
        total_6g_matches += sec_m6
        
        sim_4g = sec_m4 / max(len(sec_4g), 1) * 100
        sim_5g = sec_m5 / max(len(sec_5g), 1) * 100
        print(f'{sec_file:<26} | Words: {len(sec_toks):<5} | 4-g Overlap: {sim_4g:5.2f}% | 5-g Overlap: {sim_5g:5.2f}% | 6-g Matches: {sec_m6}')

    overall_4g = total_4g_matches / max(total_words, 1) * 100
    overall_5g = total_5g_matches / max(total_words, 1) * 100
    print('=' * 85)
    print(f'TOTAL MANUSCRIPT WORDS: {total_words}')
    print(f'OVERALL 4-GRAM SIMILARITY INDEX: {overall_4g:.3f}%')
    print(f'OVERALL 5-GRAM SIMILARITY INDEX: {overall_5g:.3f}%')
    print(f'OVERALL 6-GRAM VERBATIM MATCHES: {total_6g_matches}')
    print('=' * 85)
    
    if all_matched_phrases:
        print('EXACT 5-GRAM PHRASES FOUND:')
        for phrase, src, sec in all_matched_phrases:
            print(f'  - In {sec} (from {src}): \"{phrase}\"')
    else:
        print('ZERO VERBATIM 5-GRAM MATCHES FOUND WITH PUBLISHED LITERATURE!')
    print('=' * 85)

if __name__ == '__main__':
    main()
